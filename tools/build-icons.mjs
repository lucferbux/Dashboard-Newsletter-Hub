#!/usr/bin/env node
// Builds js/icons.js from tools/icons.txt using the official @patternfly/react-icons package
// (Red Hat UI icons = the set the RHOAI dashboard uses). No runtime dependency: the SVG path
// data is copied into a plain ES module. Run: node tools/build-icons.mjs
import { execSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '6.6.1';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const names = readFileSync(join(root, 'tools/icons.txt'), 'utf8')
  .split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));

const tmp = mkdtempSync(join(tmpdir(), 'pf-icons-'));
execSync(`npm pack @patternfly/react-icons@${VERSION} --silent`, { cwd: tmp, stdio: 'pipe' });
execSync(`tar xzf patternfly-react-icons-${VERSION}.tgz`, { cwd: tmp });
const dir = join(tmp, 'package/dist/esm/icons');

const out = {};
for (const n of names) {
  const [key, file] = n.startsWith('pf:') ? [n.slice(3), `${n.slice(3)}-icon.js`] : [n, `rh-ui-${n}-icon.js`];
  const p = join(dir, file);
  if (!existsSync(p)) { console.error(`✗ unknown icon: ${n}`); process.exitCode = 1; continue; }
  const m = /icon:\s*(\{.*?\})\s*,\s*\n/s.exec(readFileSync(p, 'utf8'));
  const icon = JSON.parse(m[1]);
  const paths = Array.isArray(icon.svgPathData) ? icon.svgPathData.map((x) => x.path ?? x) : [icon.svgPathData];
  out[key] = { w: icon.width, h: icon.height, x: icon.xOffset ?? 0, y: icon.yOffset ?? 0, d: paths };
}

const body = `// GENERATED by tools/build-icons.mjs from @patternfly/react-icons@${VERSION}. Do not edit by hand:
// add the name to tools/icons.txt and run \`node tools/build-icons.mjs\`.
export const ICONS = ${JSON.stringify(out)};

/** <svg> markup for an icon, sized by CSS (1em by default) and coloured with currentColor. */
export function icon(name, cls = '') {
  const i = ICONS[name];
  if (!i) { console.warn('Unknown icon', name); return ''; }
  return \`<svg class="mo-icon \${cls}" viewBox="\${i.x} \${i.y} \${i.w} \${i.h}" fill="currentColor" aria-hidden="true">\${i.d.map((d) => \`<path d="\${d}"/>\`).join('')}</svg>\`;
}
`;
writeFileSync(join(root, 'js/icons.js'), body);
console.log(`✓ js/icons.js — ${Object.keys(out).length} icons`);
