// Module Federation diorama: the host shell stands upright; each enabled module's pod (remote bundle +
// Go BFF) sends its UI tile into the shell. Toggling modules shows dependency resolution (autorag → gen-ai).
import { createStage, block, label, overlay, palette, glide, flow, ground, THREE } from './kit.js';

const MODS = [
  { id: 'serving', name: 'model-serving', tone: 'blue' },
  { id: 'registry', name: 'model-registry', tone: 'purple' },
  { id: 'genai', name: 'gen-ai', tone: 'green' },
  { id: 'autorag', name: 'autorag', tone: 'yellow', dep: 'genai' },
  { id: 'maas', name: 'maas', tone: 'orange' },
];

const INFO = {
  host: ['Host application shell', 'React + PatternFly. It discovers remotes declared in each package, loads their remoteEntry.js at runtime and renders the routes and nav items they expose. React and PatternFly are shared singletons — exactly one copy.'],
  config: ['federation-config', 'Generated by the Dashboard Operator: each enabled module\'s Service, port and proxy paths. A change rolls the host.'],
  pod: ['Module pod', 'Each module ships its UI bundle and its own Go BFF in its own Deployment: independent scaling, independent failures, independent releases.'],
  k8s: ['Kubernetes API', 'BFFs call the cluster on behalf of the signed-in user. The browser never talks to Kubernetes directly.'],
};

export default function moduleFederation(el) {
  const c = palette();
  const stage = createStage(el, { camera: [6, 8.5, 15.5], target: [0, 1.6, 1.6] });
  const ui = overlay(el);
  stage.scene.add(ground(10.5, c.bg));
  const on = { serving: true, registry: true, genai: true, autorag: false, maas: true };

  // Host shell (browser window)
  const host = new THREE.Group();
  host.position.set(0, 2.6, -1.6);
  host.add(block([9.4, 4.6, 0.2], c.bg, { radius: 0.18 }));
  const bar = block([9.4, 0.4, 0.06], c.border, { radius: 0.05 });
  bar.position.set(0, 2.05, 0.12);
  host.add(bar);
  const nav = block([1.4, 3.9, 0.06], c.bg2, { radius: 0.06 });
  nav.position.set(-3.85, -0.2, 0.14);
  host.add(nav);
  const hl = label('Host shell · React + PatternFly', c.brand);
  hl.position.set(0, 2.75, 0);
  host.add(hl);
  stage.scene.add(host);
  stage.pickable(host, { onClick: () => ui.show(...INFO.host, c.brand) });

  const cfg = block([1.7, 0.9, 1.2], c.orange);
  cfg.position.set(6.6, 0.45, -0.6);
  stage.scene.add(cfg);
  const cl = label('federation-config', c.orange, { small: true });
  cl.position.set(6.6, 1.25, -0.6);
  stage.scene.add(cl);
  stage.pickable(cfg, { onClick: () => ui.show(...INFO.config, c.orange) });

  const k8s = block([3.2, 0.5, 1.1], c.red);
  k8s.position.set(0, 0.25, 6.6);
  stage.scene.add(k8s);
  const kl = label('Kubernetes API', c.red, { small: true });
  kl.position.set(0, 0.9, 6.6);
  stage.scene.add(kl);
  stage.pickable(k8s, { onClick: () => ui.show(...INFO.k8s, c.red) });

  const POD_Z = 3.3;
  const podX = (i) => (i - (MODS.length - 1) / 2) * 2.6;
  const parts = MODS.map((m, i) => {
    const color = c[m.tone];
    const x = podX(i);
    const pod = block([1.9, 0.7, 1.3], color);
    pod.position.set(x, 0.35, POD_Z);
    const bff = block([1.2, 0.3, 0.5], c.bg);
    bff.position.set(x, 0.85, POD_Z + 0.3);
    const pl = label(m.name, color, { small: true });
    pl.position.set(x, 0.05, POD_Z + 1.05);
    const tile = block([2.2, 1.5, 0.12], color, { radius: 0.06 });
    tile.position.set(x, 1.4, POD_Z);
    const tl = label(m.name, color, { small: true });
    tile.add(tl);
    tl.position.set(0, 0, 0.2);
    stage.scene.add(pod, bff, pl, tile);
    stage.pickable(pod, { onClick: () => ui.show(...INFO.pod, color) });
    const move = glide(stage, tile, 4);
    return { m, pod, bff, pl, tile, tl, move, x, flows: [] };
  });

  function layout(note) {
    const enabled = MODS.filter((m) => on[m.id]);
    parts.forEach((p) => {
      const slot = enabled.findIndex((m) => m.id === p.m.id);
      const live = slot >= 0;
      const target = live ? [-1.8 + (slot % 3) * 2.45, 3.45 - Math.floor(slot / 3) * 1.75, -1.35] : [p.x, 1.4, POD_Z];
      p.move(...target);
      p.tile.visible = live;
      p.pod.material.opacity = live ? 1 : 0.25;
      p.pod.material.transparent = !live;
      p.pl.element.classList.toggle('mo-stage__label--muted', !live);
      p.flows.forEach((f) => f.remove());
      p.flows = [];
      if (live) {
        const color = c[p.m.tone];
        p.flows.push(flow(stage, [[p.x, 1.0, POD_Z], [p.x * 0.6, 2.2, 1], target], color, { count: 2, size: 0.07 }));
        p.flows.push(flow(stage, [[p.x, 0.3, POD_Z + 0.6], [p.x * 0.5, 0.3, 5.3], [0, 0.4, 6.1]], c.red, { count: 1, size: 0.06, speed: 0.3, opacity: 0.35 }));
        p.flows.forEach((f) => stage.scene.add(f));
      }
      chips[p.m.id].setAttribute('aria-pressed', String(live));
    });
    ui.show(note ? 'Dependency resolution' : 'Remotes dock into the host at runtime',
      note ?? 'Toggle a module: the operator creates or removes its Deployment, federation-config changes, and its pages dock into — or leave — the shell.', note ? c.yellow : undefined);
  }

  const chips = {};
  ui.text('Enable modules:');
  MODS.forEach((m) => {
    chips[m.id] = ui.chip(m.name, {
      pressed: on[m.id], color: c[m.tone],
      onClick: () => {
        on[m.id] = !on[m.id];
        let note = null;
        if (on[m.id] && m.dep && !on[m.dep]) { on[m.dep] = true; note = `${m.name} depends on ${MODS.find((x) => x.id === m.dep).name}: the operator's dependency pass enables it too.`; }
        if (!on[m.id]) MODS.filter((x) => x.dep === m.id && on[x.id]).forEach((x) => { on[x.id] = false; note = `Disabling ${m.name} also drops ${x.name}, which depends on it.`; });
        layout(note);
      },
    });
  });
  layout();
  return stage;
}
